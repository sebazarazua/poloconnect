const LocaleContext = createContext<LocaleContextValue | null>(null);

function interpolate(template: string, params: TranslationParams = {}) {
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    params[key] === undefined ? match : String(params[key])
  );
}

export function LocaleProvider({ children }: PropsWithChildren) {
  const { isAuthenticated } = useAuth();
  const [locale, setLocaleState] = useState<Locale>(() => readInitialLocale());

  useEffect(() => {
    if (!isAuthenticated) return;

    let cancelled = false;

    void getMySettings()
      .then((settings) => {
        if (!cancelled && isSupportedLocale(settings.locale)) {
          setLocaleState(settings.locale);
          writeStoredLocale(settings.locale);
        }
      })
      .catch(() => undefined);

    return () => {
      cancelled = true;
    };
  }, [isAuthenticated]);

  const setLocale = useCallback(
    (nextLocale: Locale) => {
      setLocaleState(nextLocale);
      writeStoredLocale(nextLocale);

      if (isAuthenticated) {
        void updateMySettings({ locale: nextLocale }).catch(() => undefined);
      }
    },
    [isAuthenticated]
  );

  const t = useCallback(
    (key: TranslationKey, params?: TranslationParams) => {
      return interpolate(translations[locale][key] ?? translations["es-AR"][key], params);
    },
    [locale]
  );

  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t
    }),
    [locale, t]
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const context = useContext(LocaleContext);

  if (!context) {
    throw new Error("useLocale must be used within a LocaleProvider");
  }

  return context;
}
