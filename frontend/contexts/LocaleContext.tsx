export type Locale = "es-AR" | "en-US";

type TranslationParams = Record<string, string | number>;
type TranslationKey = keyof typeof translations["es-AR"];

type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, params?: TranslationParams) => string;
};

export const supportedLocales: Array<{ code: Locale; label: string; nativeLabel: string; region: string }> = [
  { code: "es-AR", label: "Spanish", nativeLabel: "Español", region: "Argentina" },
  { code: "en-US", label: "English", nativeLabel: "English", region: "United States" }
];

const LOCALE_STORAGE_KEY = "pc_locale";

function isSupportedLocale(value: unknown): value is Locale {
  return supportedLocales.some((locale) => locale.code === value);
}

function mapSystemLocaleTag(tag?: string | null): Locale {
  const normalizedTag = String(tag ?? "").toLowerCase();

  if (normalizedTag.startsWith("en")) {
    return "en-US";
  }

  if (normalizedTag.startsWith("es")) {
    return "es-AR";
  }

  return "es-AR";
}

function readSystemLocale(): Locale {
  if (typeof window !== "undefined") {
    const browserLocale = window.navigator?.language ?? window.navigator?.languages?.[0];
    if (browserLocale) {
      return mapSystemLocaleTag(browserLocale);
    }
  }

  const localeTag = Localization.getLocales()?.[0]?.languageTag;
  return mapSystemLocaleTag(localeTag);
}

function readStoredLocale(): Locale {
  if (typeof window === "undefined") return "es-AR";

  try {
    const storedLocale = window.sessionStorage.getItem(LOCALE_STORAGE_KEY);
    return isSupportedLocale(storedLocale) ? storedLocale : "es-AR";
  } catch {
    return "es-AR";
  }
}

function readInitialLocale(): Locale {
  if (typeof window === "undefined") {
    return readSystemLocale();
  }

  try {
    const storedLocale = window.sessionStorage.getItem(LOCALE_STORAGE_KEY);
    if (isSupportedLocale(storedLocale)) {
      return storedLocale;
    }
  } catch {
    // Ignore session storage errors and fall back to device language.
  }

  return readSystemLocale();
}

function writeStoredLocale(locale: Locale) {
  if (typeof window === "undefined") return;

  try {
    window.sessionStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Ignore storage failures; server settings remain the source of truth after login.
  }
}

